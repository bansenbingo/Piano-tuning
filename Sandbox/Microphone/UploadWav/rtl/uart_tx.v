// =============================================================================
// uart_tx -- 参数化的 UART 发送器 (8-N-1, 无流控)
// =============================================================================
// 设计规格:
//   - 数据帧: 1 起始位 + 8 数据位 (LSB 先发) + 1 停止位
//   - 奇偶校验: 无
//   - 流控制:   无
//   - 发送空闲时 TX 线保持高电平
//   - 发送期间 busy 信号拉高, 上层模块应等待 busy 变低再发下一字节
//
// 波特率生成:
//   由 CLK_FREQ / BAUD 计算得到 DIV 分频系数。
//   例如: 100 MHz 时钟 / 921,600 bps = 108.5
//   每个 bit 持续 DIV 个时钟周期, 累计误差 < 半个时钟周期时不影响接收。
//
// 波形示意 (发送 0x55, 即 8'b0101_0101, LSB 先发):
//
//         idle  start   D0   D1   D2   D3   D4   D5   D6   D7  stop   idle
//        +-----+     +-----+-----+-----+-----+-----+-----+-----+-----+-----+
//   TX   |     |     |  1  |  0  |  1  |  0  |  1  |  0  |  1  |  0  |     |
//        |     +-----+     +-----+-----+-----+-----+-----+-----+-----+     +---
//   -----+     ^     ^                                            ^     ^
//              |     |_____ 起始位 (低电平)                        |     |_____ 停止位 (高电平)
//              |                                                  |
//              +___ 空闲 (高电平)                                 +___ 返回空闲
//
// 状态转移图:
//
//                send=1 & busy=0
//       +-------+  ---------------> +--------+
//       | IDLE  |                    | START  |
//       | tx=1  |<---+              | tx=0   |
//       | busy=0|    |              |        |
//       +-------+    |              +--------+
//                     |                  | div_cnt == DIV-1
//                     |                  v
//                     |              +--------+
//                     |              | DATA   |
//                     |   bit_idx=7  | tx=bit |
//                     |  +-----------+        |
//                     |  |           +--------+
//                     |  |              | div_cnt == DIV-1
//                     |  |   bit_idx<7  |
//                     |  |              v
//                     |  |           (next bit)
//                     |  |              |
//                     |  |              |
//                     v  v              v
//                  +--------+
//                  | STOP   |
//                  | tx=1   |
//                  +--------+
//                       | div_cnt == DIV-1
//                       v
//                  返回 IDLE
//
// =============================================================================

module uart_tx #(
    parameter CLK_FREQ = 100_000_000,    // 系统时钟频率 (Hz), 默认 100 MHz
    parameter BAUD     = 921_600         // UART 波特率 (bps), 默认 921.6 kbps
) (
    input  wire       clk,               // 系统时钟
    input  wire       rst,               // 同步复位 (高有效)
    input  wire [7:0] data,              // 待发送的 8-bit 数据字节
    input  wire       send,              // 发送触发脉冲 (高有效, 持续 1 拍即可)
    output reg        busy,              // 忙标志: 1=正在发送, 0=空闲可接收新数据
    output reg        tx                 // UART TX 串行输出
);

    // ---- 波特率分频参数 ----
    // DIV: 每个 bit 持续多少个系统时钟周期
    // 整数截断误差对非整数波特率是容许的 (容差 < ±0.5)
    localparam DIV   = CLK_FREQ / BAUD;
    // DIV_W: div_cnt 计数器所需的位宽 ($clog2 取 ceil(log2))
    localparam DIV_W = $clog2(DIV) + 1;

    // ---- FSM 状态编码 (独热码不必要, 3-bit 够用) ----
    localparam S_IDLE  = 3'd0;           // 空闲, 等待 send
    localparam S_START = 3'd1;           // 发送起始位 (拉低 TX)
    localparam S_DATA  = 3'd2;           // 逐 bit 发送 8 位数据, LSB 优先
    localparam S_STOP  = 3'd3;           // 发送停止位 (拉高 TX)

    // ---- 内部寄存器 ----
    reg [2:0]       state;               // 当前 FSM 状态
    reg [DIV_W-1:0] div_cnt;             // 波特率分频计数器 (0 ~ DIV-1)
    reg [2:0]       bit_idx;             // 当前发送的数据位索引 (0~7)
    reg [7:0]       shift_reg;           // 待发送数据的移位寄存器 (LSB 优先移出)

    // =========================================================================
    // 主 FSM: 同步复位 + 分频计数 + 状态转移
    // =========================================================================
    always @(posedge clk) begin
        if (rst) begin
            // ---- 复位: 回到空闲, 所有寄存器清零 ----
            state     <= S_IDLE;
            div_cnt   <= 0;
            bit_idx   <= 0;
            shift_reg <= 0;
            busy      <= 1'b0;           // 空闲
            tx        <= 1'b1;           // 空闲态 TX 保持高电平
        end else begin
            case (state)

                // -----------------------------------------------------------------
                // S_IDLE: 等待 send 脉冲
                // - busy=0 告知上层可以发送
                // - tx=1 (空闲高电平, 符合 UART 协议)
                // - 检测到 send=1 时锁存数据, 立即进入 START 状态
                // -----------------------------------------------------------------
                S_IDLE: begin
                    busy <= 1'b0;
                    tx   <= 1'b1;
                    if (send) begin
                        shift_reg <= data;    // 锁存待发送数据 (防止发送期间 data 变化)
                        state     <= S_START;
                        div_cnt   <= 0;
                        busy      <= 1'b1;    // 置忙, 禁止上层写新数据
                    end
                end

                // -----------------------------------------------------------------
                // S_START: 输出起始位 (低电平), 持续 DIV 个时钟周期
                // - 起始位固定为 0, 通知接收端帧传输开始
                // - 分频计数到达 DIV-1 后进入 DATA 状态
                // -----------------------------------------------------------------
                S_START: begin
                    tx <= 1'b0;               // 起始位: 拉低
                    if (div_cnt == DIV - 1) begin
                        div_cnt <= 0;
                        bit_idx <= 3'b0;       // 从 bit 0 (LSB) 开始发送
                        state   <= S_DATA;
                    end else begin
                        div_cnt <= div_cnt + 1'b1;
                    end
                end

                // -----------------------------------------------------------------
                // S_DATA: 逐 bit 发送 8 位数据, LSB 优先
                // - tx 输出 shift_reg 当前 bit_idx 对应位
                // - 每个 bit 持续 DIV 个时钟周期
                // - bit_idx == 7 表示已到最高位 (MSB), 下一状态进入 STOP
                // - 注意: shift_reg 内容在整个数据阶段保持不变
                // -----------------------------------------------------------------
                S_DATA: begin
                    tx <= shift_reg[bit_idx]; // 输出当前位
                    if (div_cnt == DIV - 1) begin
                        div_cnt <= 0;
                        if (bit_idx == 3'd7) begin
                            state <= S_STOP;  // 8 位已全部发出, 进入停止位
                        end else begin
                            bit_idx <= bit_idx + 1'b1;
                        end
                    end else begin
                        div_cnt <= div_cnt + 1'b1;
                    end
                end

                // -----------------------------------------------------------------
                // S_STOP: 输出停止位 (高电平), 持续 DIV 个时钟周期
                // - 停止位为 1, 恢复空闲电平
                // - 分频计数到达 DIV-1 后返回 IDLE, 完成一帧传输
                // - 此时拉低 busy, 上层可以发送下一字节
                // -----------------------------------------------------------------
                S_STOP: begin
                    tx <= 1'b1;               // 停止位: 拉高
                    if (div_cnt == DIV - 1) begin
                        state <= S_IDLE;       // 帧传输完毕, 返回空闲
                        busy  <= 1'b0;         // 释放忙标志
                    end else begin
                        div_cnt <= div_cnt + 1'b1;
                    end
                end

                // ---- 未定义状态的保护: 强制回到 IDLE ----
                default: state <= S_IDLE;
            endcase
        end
    end

endmodule
